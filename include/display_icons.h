// ============================================================================
//  display_icons.h —— OLED 图标（数据来自 u8g2 官方字体）
//
//  【数据来源】
//    · 电池：外框取自 u8g2 官方 tools/font/bdf/open_iconic_all_1x.bdf 里的
//            battery-empty.png (ENCODING=90)，8x8；
//            内部填充按电量比例计算，共 5 档。100% 档与官方 battery-full.png
//            (ENCODING=91) 逐像素一致。
//    · 蓝牙：官方同一字体的 bluetooth.png (ENCODING=94)，8x8。
//
//  【格式】列优先页格式（和 SSD1306 帧缓冲一致）：每列 1 字节，bit0 = 最上像素。
//          8x8 图标正好每列 1 字节，可以直接写进页。
//
//  【为什么不直接用 u8g2 的 8x19 battery19.bdf】
//    那个字体是 8 宽 19 高、7 档，但 19 像素在 32 像素高的屏上占 60%，
//    而且列数据会跨页，反而更复杂。官方的 8x8 版本更合适。
//
//  【校验】tools/verify_icons.py 会把这里的位图反解成 ASCII 逐格核对，
//          并与官方 battery-empty / battery-full 对比。
// ============================================================================
#pragma once

#include <stdint.h>

// ---------------------------------------------------------------- 电池图标
#define ICON_BAT_W       8
#define ICON_BAT_H       8
#define ICON_BAT_LEVELS  5      // 0% / 25% / 50% / 75% / 100%

// 形状（# = 点亮）：
//    0%        25%       50%       75%       100%
//   ........  ........  ........  ........  ........
//   #######.  #######.  #######.  #######.  #######.
//   #.....#.  ##....#.  ###...#.  #####.#.  #######.
//   #.....##  ##....##  ###...##  #####.##  ########
//   #.....##  ##....##  ###...##  #####.##  ########
//   #.....#.  ##....#.  ###...#.  #####.#.  #######.
//   #######.  #######.  #######.  #######.  #######.
//   ........  ........  ........  ........  ........
static const uint8_t ICON_BAT[ICON_BAT_LEVELS][ICON_BAT_W] = {
    { 0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x18 },  // 0%
    { 0x7E, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x18 },  // 25%
    { 0x7E, 0x7E, 0x7E, 0x42, 0x42, 0x42, 0x7E, 0x18 },  // 50%
    { 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x42, 0x7E, 0x18 },  // 75%
    { 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x18 },  // 100%
};

// ---------------------------------------------------------------- 蓝牙图标
