//   ...##...
//   .##..#..
//   ..###...
//   ..###...
//   .##..#..
//   ...##...
//   ...#....
#define ICON_BT_W   8
#define ICON_BT_H   8

static const uint8_t ICON_BT[ICON_BT_W] = {
    0x00, 0x24, 0x3C, 0xDB, 0x5A, 0x24, 0x00, 0x00
};
