// ============================================================================
//  board_config.h —— 板级配置：这块板所有引脚都只在这里定义
//
//  依据：原理图 "Schematic1 / Board1 V1.0"（智能桌面小键盘，嘉立创EDA）
//
//  改硬件只改这个文件，其余代码一律不碰。
// ============================================================================
#pragma once

// ============================================================================
//  WS2812B-2020-V6 × 5 —— 串在 5 个按键上，级联
// ============================================================================
// GPIO1 --(R13 100R)--> LED1 DI；LED1.DO -> LED2.DI -> ... -> LED5.DO 悬空
#define LED_DATA_PIN               1
#define LED_COUNT                  5

// 全局亮度 0..255。5 颗全白峰值约 5 x 35mA = 175mA；
// 本板灯珠是 3V3 直供（经 U6 高边开关），首次点亮建议 <=128，别超过 3V3 轨余量。
#define LED_BRIGHTNESS             96

// ------------------------------------------------- 灯珠电源高边开关 U6 (AO3401)
// P-MOS 高边开关：源极 3V3、漏极接灯珠 VDD 轨、栅极接 GPIO21（经 R17 10K 上拉）
// P-MOS 特性 -> 栅极拉低才导通
#define LED_POWER_SWITCH_PRESENT   1
#define LED_POWER_PIN              21
#define LED_POWER_ACTIVE_LOW       1

// ============================================================================
//  灯效切换开关 U4 (SH-1806SA) —— GPIO6
//
//  原理图里 U4 一端接 GPIO6、另一端接 GND，用芯片内部上拉。
//  所以"闭合/拨到接通位" = 读到低电平。
//
//  固件行为：每次检测到有效翻转（低->高 或 高->低）就切到下一个灯效。
//  这样无论 U4 是"点动按钮"还是"拨动开关"都能用：
//    - 点动：每按一下切一次
//    - 拨动：来回拨，每拨一次切一次
//  极性不用管（两个方向都算一次翻转），所以接反了也能工作。
// ============================================================================
#define LED_EFFECT_SWITCH_PRESENT  1
#define LED_EFFECT_SWITCH_PIN      6
#define LED_EFFECT_SWITCH_ACTIVE_LOW 1   // 开关到 GND 时读到低电平
#define LED_EFFECT_SWITCH_DEBOUNCE_MS 40

// ============================================================================
//  按键 K1..K5 —— 一端接 GPIO，另一端接 GND（R3~R5 为 0Ω 串联）
//  按下为低电平，用芯片内部上拉
// ============================================================================
#define BUTTON_COUNT               5
#define BTN1_PIN                   0     // K1  (strapping 脚：上电别按住，否则进下载模式)
#define BTN2_PIN                   2     // K2  (strapping 脚，板上 R6 10K 上拉)
#define BTN3_PIN                   20    // K3  (同时是 UART0 RXD 默认脚 —— 所以日志必须走 USB)
#define BTN4_PIN                   7     // K4
#define BTN5_PIN                   8     // K5  (strapping 脚，板上 R8 10K 上拉；上电别按住)

// 消抖时间。机械轴抖动一般 <5ms，20ms 足够且手感不钝
#define BUTTON_DEBOUNCE_MS         20
// 长按判定（原工程 LONG_PRESS_TIME = 2000ms）
#define BUTTON_LONG_PRESS_MS       2000

// ============================================================================
//  OLED —— SSD1306 128×32，走硬件 I2C
//  板上是 4 针排针，丝印 GND / 3V3 / SCL / SDA
//
//  【地址必须写 0x3C，不能写 0x78 —— 这是本板实机踩到的坑】
//    原工程用的是软件 bit-bang I2C，IIC_SendByte() 直接把地址字节发出去，
//    所以那边写 0x78（= 0x3C << 1，8 位形式）是对的。
//    但 Arduino 的 Wire 库吃的是 **7 位地址**，内部会自己左移一位再补读写位。
//    这里如果照抄 0x78，总线上实际发出的是 0xF0 —— 面板不会有任何应答，
//    表现就是"OLED 死活不亮，但扫描整条 I2C 总线能在 0x3C 找到设备"。
//    （另外原理图上这个排针的网络名是 SCL/SDA 接到了 GPIO4/5，
//      但图上那两根线被标成了 SCK/SDA，属于原理图符号遗留，实际接线没错。）
// ============================================================================
#define OLED_I2C_ADDR              0x3C      // 7 位地址，Wire 用这个（不是 0x78！）
#define OLED_WIDTH                 128
#define OLED_HEIGHT                32
#define OLED_SDA_PIN               4     // GPIO4 -> OLED SDA
#define OLED_SCL_PIN               5     // GPIO5 -> OLED SCL
#define OLED_I2C_HZ                400000
// 整屏刷新的最小间隔(ms)。128x32 整屏 512 字节 + 控制字节，400kHz 下约 12ms
#define OLED_FLUSH_INTERVAL_MS     40

// ============================================================================
//  蜂鸣器 BUZ1 2.7kHz —— GPIO10 -> R10 1K -> Q1 S9013 基极（NPN 低边）
//  蜂鸣器正极接 3V3，D3 1N4148WS 续流。GPIO10 = 高电平 -> 导通 -> 响
// ============================================================================
#define BUZZER_PIN                 10
// 无源蜂鸣器的驱动频率；本板是 2.7kHz 规格，留一点余量取 2700
#define BUZZER_FREQ                2700
#define BUZZER_ENABLED             1

// ============================================================================
//  电池电压检测 —— BAT+ -> R9 100K -> GPIO3 -> R15 100K -> GND，C6 100nF 滤波
//
//  这个脚在原理图里是空出来的（原工程的 A0/GPIO0 是错的，GPIO0 是 K1）。
//  分压比 = R15/(R9+R15) = 100K/200K = 0.5
//    4.20V 满电 -> 2.10V  (GPIO3 能承受，ADC 量程内)
//    3.30V 低电 -> 1.65V
//    2.64V 空电 -> 1.32V
//
//  注意：GPIO3 是 ADC1_CH3，只做模拟输入，绝不能当输出驱动。
//
//  ---------------------------------------------------------------------------
//  【重要】没接电池时，BAT+ 上会有 4.2V，这不是故障
//  ---------------------------------------------------------------------------
//  TP4056 没接电池时处于恒压(CV)环路空载状态，BAT 脚会一直顶在 4.2V 调节点。
//  它判断"充满"靠的是充电电流跌到设定值的 1/10 以下（R20 2.4K -> 500mA，
//  即 50mA）。而本板 100K/100K 分压只抽走 4.2V/200K = 21uA，比 50mA 小三个
//  数量级，所以 TP4056 永远不会判定充满 —— CHRG 红灯会常亮，BAT+ 恒为 4.2V。
//
//  因此：**光靠 BAT+ 电压无法在软件上区分"没装电池"和"电池已充满"**
//  （两者都是 4.2V，纹波都在 ADC 噪声量级；要区分得测充电电流，硬件上没引出）。
//  所以这里用一个明确的开关，而不是让软件瞎猜：
//
//    BATTERY_PRESENT = 0  -> 不采 ADC，OLED 显示 "USB" 而不是电量百分比
//    BATTERY_PRESENT = 1  -> 正常显示电压和电量（装上电池后再打开）
//
//  也可以运行时切换：串口发 't'
// ============================================================================
#define BATTERY_ENABLED            1
#define BATTERY_PRESENT            0       // <-- 没装电池就保持 0
#define BATTERY_ADC_PIN            3
#define BATTERY_DIVIDER            0.5f     // (R9+R15) 比值：Vbat = Vadc / 0.5
#define BATTERY_READ_INTERVAL_MS   10000UL  // 10s 读一次
#define BATTERY_SAMPLES            16       // 每次读的采样平均次数

// 电量区间（单节锂电，空载近似）
#define BAT_FULL_V                 4.20f
#define BAT_LOW_V                  3.30f    // 低于此值判为低电 -> OLED 降亮度
#define BAT_EMPTY_V                2.64f

// 校准微调：如果 OLED 显示的电压与万用表实测不符，改这个系数
// 实测电压 = 芯片读数(V) / BATTERY_DIVIDER * BATTERY_CAL
#define BATTERY_CAL                1.0f

// ============================================================================
//  其它
// ============================================================================
// 串口 / 调试日志走 USB Serial/JTAG，完全不占用按键、灯珠电源脚
#define ENABLE_SERIAL_LOG          1
#define SERIAL_BAUD                115200

// BLE 设备名与制造商（会出现在电脑蓝牙列表里）
#define BLE_DEVICE_NAME            "ESP32-C3 Keybrick"
#define BLE_DEVICE_MANUFACTURER    "WilliTourt"
